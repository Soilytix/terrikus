/**
 * Packs the organism sprites and group badges (src/assets/organisms/) into one
 * SVG sheet plus its frame table, so a scene layer draws every organism from a
 * single texture and so in one draw call (backlog T12). Run after editing a sprite:
 *   mise exec -- pnpm exec tsx tools/atlas.ts
 * tests/organisms.test.ts fails when the sheet or the table drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";
import { BADGE_SHAPES, CAST } from "../src/assets/organisms/cast";

const DIR = "src/assets/organisms";
export const SHEET_SVG = `${DIR}/atlas.svg`;
export const FRAMES_TS = "src/world/atlas-frames.ts";
/** Gap between frames, so linear sampling never bleeds a neighbour in. */
const PAD = 2;
const SHEET_WIDTH = 512;

export interface Frame {
  x: number;
  y: number;
  w: number;
  h: number;
}

/** Shelf packing, tallest first; deterministic for a given input order. */
export function pack(items: { id: string; w: number; h: number }[], width: number) {
  const frames: Record<string, Frame> = {};
  let x = PAD;
  let y = PAD;
  let shelf = 0;
  for (const it of [...items].sort((a, b) => b.h - a.h || b.w - a.w)) {
    if (x + it.w + PAD > width) {
      x = PAD;
      y += shelf + PAD;
      shelf = 0;
    }
    frames[it.id] = { x, y, w: it.w, h: it.h };
    x += it.w + PAD;
    shelf = Math.max(shelf, it.h);
  }
  return { frames, w: width, h: y + shelf + PAD };
}

function sources() {
  return [
    ...CAST.map((o) => ({ id: o.id, file: `${DIR}/${o.id}.svg` })),
    ...BADGE_SHAPES.map((b) => ({ id: `badge-${b}`, file: `${DIR}/badges/${b}.svg` })),
  ].map(({ id, file }) => {
    const svg = readFileSync(file, "utf8");
    const box = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
    if (!box) throw new Error(`${file}: no "0 0 w h" viewBox`);
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/<title>.*?<\/title>\s*/, "");
    return { id, w: Number(box[1]), h: Number(box[2]), inner: inner.trim() };
  });
}

export async function buildAtlas(): Promise<{ svg: string; ts: string }> {
  const items = sources();
  const { frames, w, h } = pack(items, SHEET_WIDTH);
  const nested = items.map((it) => {
    const f = frames[it.id] as Frame;
    return `<svg x="${f.x}" y="${f.y}" width="${f.w}" height="${f.h}" viewBox="0 0 ${f.w} ${f.h}">\n${it.inner}\n</svg>`;
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">\n<!-- Generated by tools/atlas.ts; edit the sprites, not this sheet. -->\n${nested.join("\n")}\n</svg>\n`;
  const ts = await format(
    `/** Generated by tools/atlas.ts from src/assets/organisms/: frames of organisms/atlas.svg, in sheet units. */
export const ATLAS = ${JSON.stringify({ w, h, frames })} as const;

export type AtlasFrameId = keyof typeof ATLAS.frames;
`,
    { ...(await resolveConfig(FRAMES_TS)), filepath: FRAMES_TS },
  );
  return { svg, ts };
}

if (process.argv[1]?.endsWith("atlas.ts")) {
  const { svg, ts } = await buildAtlas();
  writeFileSync(SHEET_SVG, svg);
  writeFileSync(FRAMES_TS, ts);
  console.log(`wrote ${SHEET_SVG} and ${FRAMES_TS}`);
}
