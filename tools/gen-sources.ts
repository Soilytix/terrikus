/**
 * Generates src/content/sources.ts from the tables in docs/sources.md, which is
 * the bibliography of record. Run after editing the doc:
 *   mise exec -- pnpm exec tsx tools/gen-sources.ts
 * tests/content-lint.test.ts fails when the two drift.
 */
import { readFileSync, writeFileSync } from "node:fs";

export interface SourceRow {
  id: string;
  citation: string;
  link: string;
  reuse: string;
  status: string;
}

export function parseSourcesDoc(md: string): SourceRow[] {
  const rows: SourceRow[] = [];
  for (const line of md.split("\n")) {
    const m = line.match(/^\|\s*`([a-z0-9][a-z0-9-]*)`\s*\|(.*)\|\s*$/);
    if (!m) continue;
    const cells = (m[2] as string).split(/\s\|\s/).map((c) => c.trim());
    rows.push({
      id: m[1] as string,
      citation: cells[0] ?? "",
      link: cells[1] ?? "",
      reuse: cells[2] ?? "",
      status: cells[3] ?? "",
    });
  }
  return rows;
}

/** Agencies whose full name is too long for a label. */
const AGENCY_SHORT: Record<string, string> = {
  "Soil Science Society of America": "SSSA",
  "University of Minnesota Extension": "UMN Extension",
  "Heinrich Böll Stiftung": "Böll Stiftung",
  "Cornell Nutrient Management Spear Program": "Cornell",
  "Cornell Soil Health Lab": "Cornell",
  "IUSS Working Group WRB": "IUSS WRB",
};

/** Citations with no author or year in the usual place. */
const SHORT_OVERRIDE: Record<string, string> = {
  "van-helmont-willow": "van Helmont 1648",
  "frontiers-2023-bacillus-fj3": "Front. Plant Sci. 2023",
};

const INITIALS = /^(?:[A-Z][a-z]?\.[\s-]*)+$/;

/**
 * "Weil & Brady 2017", "Six et al. 2004", "FAO & ITPS 2015": first author surname,
 * both for two, et al. beyond; an agency's short name; the year when there is one.
 */
export function shortLabel(id: string, citation: string): string {
  if (SHORT_OVERRIDE[id]) return SHORT_OVERRIDE[id];
  const plain = citation.replace(/[*`]/g, "");
  const m = plain.match(/^(.*?)\s*\((\d{4})\)/);
  const year = m?.[2];
  const head = (m ? m[1] : plain.split(/\s\(/)[0]!.split(/\.\s(?=[A-Z][a-z])/)[0]) as string;
  const authors = head.replace(/\s*\(eds?\.\)/, "").replace(/(\S\S)\.\s*$/, "$1");
  const parts = authors
    .split(/\s\/\s/)[0]!
    .split(/,\s|\s&\s/)
    .map((t) => t.trim());
  const etAl = parts.some((t) => /\bet al\.?$/.test(t));
  const names = parts
    .map((t) => t.replace(/\s*et al\.?$/, ""))
    .filter((t) => t && !INITIALS.test(t))
    .map((t) => AGENCY_SHORT[t] ?? t);
  const who = etAl || names.length > 2 ? `${names[0]} et al.` : names.join(" & ");
  return year ? `${who} ${year}` : who;
}

if (process.argv[1]?.endsWith("gen-sources.ts")) {
  const rows = parseSourcesDoc(readFileSync("docs/sources.md", "utf8"));
  const body = rows
    .map(
      (r) =>
        `  ${JSON.stringify(r.id)}: { short: ${JSON.stringify(shortLabel(r.id, r.citation))}, citation: ${JSON.stringify(r.citation)}, link: ${JSON.stringify(
          r.link,
        )}, status: ${JSON.stringify(r.status)} },`,
    )
    .join("\n");
  const out = `// GENERATED by tools/gen-sources.ts from docs/sources.md. Do not edit by hand.
export const SOURCES = {
${body}
} as const satisfies Record<string, { short: string; citation: string; link: string; status: string }>;

export type SourceId = keyof typeof SOURCES;
`;
  writeFileSync("src/content/sources.ts", out);
  console.log(`wrote ${rows.length} sources`);
}
