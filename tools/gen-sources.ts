/**
 * Generates src/content/sources.ts from the tables in docs/sources.md, which is
 * the bibliography of record. Run after editing the doc:
 *   mise exec -- pnpm exec tsx tools/gen-sources.ts
 * tests/content-lint.test.ts fails when the two drift.
 */
import { readFileSync, writeFileSync } from "node:fs";

export interface SourceRow {
  id: string;
  citation: string;
  link: string;
  reuse: string;
  status: string;
}

export function parseSourcesDoc(md: string): SourceRow[] {
  const rows: SourceRow[] = [];
  for (const line of md.split("\n")) {
    const m = line.match(/^\|\s*`([a-z0-9][a-z0-9-]*)`\s*\|(.*)\|\s*$/);
    if (!m) continue;
    const cells = (m[2] as string).split(/\s\|\s/).map((c) => c.trim());
    rows.push({
      id: m[1] as string,
      citation: cells[0] ?? "",
      link: cells[1] ?? "",
      reuse: cells[2] ?? "",
      status: cells[3] ?? "",
    });
  }
  return rows;
}

if (process.argv[1]?.endsWith("gen-sources.ts")) {
  const rows = parseSourcesDoc(readFileSync("docs/sources.md", "utf8"));
  const body = rows
    .map(
      (r) =>
        `  ${JSON.stringify(r.id)}: { citation: ${JSON.stringify(r.citation)}, link: ${JSON.stringify(
          r.link,
        )}, status: ${JSON.stringify(r.status)} },`,
    )
    .join("\n");
  const out = `// GENERATED by tools/gen-sources.ts from docs/sources.md. Do not edit by hand.
export const SOURCES = {
${body}
} as const satisfies Record<string, { citation: string; link: string; status: string }>;

export type SourceId = keyof typeof SOURCES;
`;
  writeFileSync("src/content/sources.ts", out);
  console.log(`wrote ${rows.length} sources`);
}
